package database

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestCheckedInSQLCOutputIdentifiesPinnedGeneratorAndQueries(t *testing.T) {
	t.Parallel()
	root := filepath.Join("dbgen")
	entries, err := os.ReadDir(root)
	if err != nil {
		t.Fatal(err)
	}
	required := map[string]bool{
		"access.sql.go": false, "preset.sql.go": false,
		"tracker.sql.go": false, "reliability.sql.go": false,
	}
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".go") {
			continue
		}
		content, readErr := os.ReadFile(filepath.Join(root, entry.Name()))
		if readErr != nil {
			t.Fatal(readErr)
		}
		if !strings.Contains(string(content), "Code generated by sqlc. DO NOT EDIT.") ||
			!strings.Contains(string(content), "sqlc v1.30.0") {
			t.Fatalf("%s is not pinned sqlc output", entry.Name())
		}
		if _, ok := required[entry.Name()]; ok {
			required[entry.Name()] = true
		}
	}
	for name, found := range required {
		if !found {
			t.Fatalf("missing generated query file %s", name)
		}
	}
}
