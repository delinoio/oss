import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";

export const consumers = ["app", "build-consumer", "dev-consumer", "indirect-consumer", "optional-consumer", "target-consumer"];
export const fixtureNames = [...consumers, "core-lib", "unrelated", "forge-scene", "pnport", "pnport-preload"].sort();
export function rustFixture(t) {
  const cwd = realpathSync(mkdtempSync(join(tmpdir(), "rust-ci-fixture-")));
  t.after(() => rmSync(cwd, { recursive: true, force: true }));
  const git = (...args) => execFileSync("git", args, { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] }).trim();
  const write = (path, value) => { mkdirSync(dirname(join(cwd, path)), { recursive: true }); writeFileSync(join(cwd, path), value); };
  git("init", "-b", "main");
  git("config", "user.name", "CI Fixture"); git("config", "user.email", "ci@example.invalid");
  git("config", "commit.gpgsign", "false"); git("config", "core.hooksPath", join(cwd, "empty-hooks"));
  write("Cargo.toml", `[workspace]\nresolver = "2"\nmembers = ${JSON.stringify(fixtureNames)}\n`);
  for (const name of fixtureNames) {
    let manifest = `[package]\nname = "${name}"\nversion = "0.1.0"\nedition = "2021"\n`;
    if (consumers.includes(name)) {
      const kind = name === "build-consumer" ? "build-dependencies" : name === "dev-consumer" ? "dev-dependencies" : name === "target-consumer" ? "target.'cfg(windows)'.dependencies" : "dependencies";
      const dependency = name === "indirect-consumer" ? "app" : "core-lib";
      manifest += `[${kind}]\n${dependency} = { path = "../${dependency}"${name === "optional-consumer" ? ", optional = true" : ""} }\n`;
    }
    write(`${name}/Cargo.toml`, manifest);
    write(`${name}/src/lib.rs`, "pub fn value() -> u32 { 1 }\n");
    // A workspace-wide invocation would fail here. Successful live commands
    // therefore prove that an unaffected package was not compiled or tested.
    if (name === "unrelated") write(`${name}/src/lib.rs`, 'compile_error!("unaffected workspace package must not be compiled");\n');
    if (name === "build-consumer") write(`${name}/build.rs`, "fn main() {}\n");
  }
  write("Cargo.lock", `# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n${fixtureNames.map(name => `\n[[package]]\nname = "${name}"\nversion = "0.1.0"\n${consumers.includes(name) ? `dependencies = [\n "${name === "indirect-consumer" ? "app" : "core-lib"}",\n]\n` : ""}`).join("")}`);
  const commit = () => { git("add", "--all"); git("commit", "-m", "fixture"); return git("rev-parse", "HEAD"); };
  const base = commit();
  const paths = (from, head) => execFileSync("git", ["diff", "--name-only", "--no-renames", "-z", from, head, "--"], { cwd, encoding: "utf8" }).split("\0").filter(Boolean);
  const range = (from = base, head = git("rev-parse", "HEAD")) => ({ base: from, head, paths: paths(from, head) });
  const plan = { jobs: { "rust-test": true, "rust-clippy": true }, forced: { "rust-test": false, "rust-clippy": false } };
  const binary = join(cwd, "unused-cargo-mono");
  const run = (_file, args, workspace, env) => {
    if (args.includes("list")) return { workspace_root: workspace, packages: fixtureNames.map(name => ({ name, version: "0.1.0", manifest_path: `${name}/Cargo.toml`, publishable: false })) };
    const from = args.at(-1);
    const mergeBase = execFileSync("git", ["merge-base", from, "HEAD"], { cwd: workspace, encoding: "utf8" }).trim();
    const files = execFileSync("git", ["diff", "--name-only", mergeBase, "HEAD"], { cwd: workspace, env, encoding: "utf8" }).trim().split("\n").map(value => value.trim()).filter(Boolean);
    const direct = fixtureNames.filter(name => files.some(path => path.startsWith(name + "/") && !path.endsWith("/AGENTS.md")));
    const packages = [...new Set([...direct, ...(direct.includes("core-lib") ? consumers : direct.includes("app") ? ["indirect-consumer"] : [])])].sort();
    return { workspace_root: workspace, base_ref: from, merge_base: mergeBase, include_uncommitted: false, direct_only: false, files, packages };
  };
  return { cwd, git, write, read: path => readFileSync(join(cwd, path), "utf8"), commit, base, range, plan, binary, run };
}
